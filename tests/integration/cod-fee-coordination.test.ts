import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { randomUUID } from 'node:crypto';
import pg from 'pg';

// Disposable, synthetic SQL experiment only. Not a production schema, finance
// journal, cash collection protocol, or implementation of checkout/dispatch.
const rawUrl = process.env.TEST_DATABASE_MIGRATION_URL;
function disposableUrl(): string {
  if (!rawUrl) throw new Error('TEST_DATABASE_MIGRATION_URL required');
  const url = new URL(rawUrl);
  if (!['localhost', '127.0.0.1', '[::1]'].includes(url.hostname) || url.pathname !== '/getstoopy_test' || url.username !== 'gs_owner') throw new Error('DISPOSABLE_TEST_DATABASE_REQUIRED');
  // These checks cannot detect a loopback proxy to a valuable database.
  return rawUrl;
}
const suffix = randomUUID().replaceAll('-', '');
// Only generated identifiers are interpolated; all data is parameterized.
const orders = `"fixture_cod_orders_${suffix}"`;
const deliveries = `"fixture_cod_deliveries_${suffix}"`;
const claims = `"fixture_cod_claims_${suffix}"`;
const connect = async () => { const c = new pg.Client({ connectionString: disposableUrl() }); await c.connect(); return c; };
async function transaction<T>(fn: (c: pg.Client) => Promise<T>): Promise<T> {
  const c = await connect();
  try { await c.query('BEGIN'); const result = await fn(c); await c.query('COMMIT'); return result; }
  catch (err) { await c.query('ROLLBACK'); throw err; }
  finally { await c.end(); }
}
async function setupOrder(deliveryCount: number) {
  const order = randomUUID(); const ids = Array.from({ length: deliveryCount }, () => randomUUID());
  await transaction(async c => {
    await c.query(`INSERT INTO ${orders} (id) VALUES ($1)`, [order]);
    for (const id of ids) await c.query(`INSERT INTO ${deliveries} (id, order_id, state) VALUES ($1,$2,'PENDING')`, [id, order]);
  });
  return { order, ids };
}
async function lockOrder(c: pg.Client, order: string) {
  const r = await c.query(`SELECT id FROM ${orders} WHERE id=$1 FOR UPDATE`, [order]);
  if (!r.rowCount) throw new Error('ORDER_NOT_FOUND');
}
async function changeAttempt(order: string, id: string, from: string, to: string) {
  return transaction(async c => {
    await lockOrder(c, order);
    const r = await c.query(`UPDATE ${deliveries} SET state=$4 WHERE order_id=$1 AND id=$2 AND state=$3`, [order, id, from, to]);
    if (r.rowCount !== 1) throw new Error('ATTEMPT_STATE_INVALID');
  });
}
/** All participants in this toy protocol must lock the same order row. */
async function complete(order: string, id: string, abortBeforeCommit = false) {
  return transaction(async c => {
    await lockOrder(c, order);
    const row = await c.query(`SELECT state FROM ${deliveries} WHERE order_id=$1 AND id=$2`, [order, id]);
    if (!row.rowCount) throw new Error('DELIVERY_NOT_FOUND');
    if (row.rows[0].state === 'SUCCEEDED') {
      const prior = await c.query(`SELECT delivery_id FROM ${claims} WHERE order_id=$1`, [order]);
      return { replay: true, feeCandidate: prior.rows[0]?.delivery_id === id };
    }
    if (row.rows[0].state !== 'PENDING') throw new Error('ATTEMPT_STATE_INVALID');
    await c.query(`UPDATE ${deliveries} SET state='SUCCEEDED' WHERE order_id=$1 AND id=$2`, [order, id]);
    const remaining = await c.query(`SELECT count(*)::int AS n FROM ${deliveries} WHERE order_id=$1 AND state <> 'SUCCEEDED'`, [order]);
    const feeCandidate = remaining.rows[0].n === 0;
    if (feeCandidate) await c.query(`INSERT INTO ${claims} (order_id,delivery_id) VALUES ($1,$2)`, [order, id]);
    if (abortBeforeCommit) throw new Error('SYNTHETIC_ABORT');
    return { replay: false, feeCandidate };
  });
}
async function snapshot(order: string) {
  const c = await connect();
  try {
    const states = await c.query(`SELECT id,state FROM ${deliveries} WHERE order_id=$1 ORDER BY id`, [order]);
    const fees = await c.query(`SELECT delivery_id FROM ${claims} WHERE order_id=$1`, [order]);
    return { states: states.rows, fees: fees.rows };
  } finally { await c.end(); }
}

beforeAll(async () => {
  await transaction(async c => {
    await c.query(`CREATE TABLE ${orders} (id uuid PRIMARY KEY)`);
    await c.query(`CREATE TABLE ${deliveries} (id uuid PRIMARY KEY, order_id uuid NOT NULL REFERENCES ${orders}(id), state text NOT NULL CHECK (state IN ('PENDING','FAILED','SUCCEEDED')), UNIQUE(order_id,id))`);
    await c.query(`CREATE TABLE ${claims} (order_id uuid PRIMARY KEY, delivery_id uuid NOT NULL, FOREIGN KEY (order_id,delivery_id) REFERENCES ${deliveries}(order_id,id))`);
  });
});
afterAll(async () => {
  // Only names generated by this process; do not run this suite on valuable data.
  await transaction(async c => { await c.query(`DROP TABLE IF EXISTS ${claims}, ${deliveries}, ${orders}`); });
});

describe('disposable COD fee candidate concurrency experiment', () => {
  it('locks the order against a competing transaction', async () => {
    const { order, ids } = await setupOrder(1);
    const a = await connect(); const b = await connect();
    try {
      await a.query('BEGIN'); await lockOrder(a, order);
      await b.query('BEGIN'); await b.query("SET LOCAL lock_timeout = '200ms'");
      await expect(lockOrder(b, order)).rejects.toMatchObject({ code: '55P03' });
    } finally {
      await b.query('ROLLBACK'); await a.query('ROLLBACK'); await b.end(); await a.end();
    }
    expect((await complete(order, ids[0]!)).feeCandidate).toBe(true);
  });
  it('serializes simultaneous successful completions and records exactly one candidate', async () => {
    const { order, ids } = await setupOrder(6);
    const results = await Promise.all(ids.map(id => complete(order, id)));
    expect(results.filter(r => r.feeCandidate)).toHaveLength(1);
    const snap = await snapshot(order);
    expect(snap.states.every(s => s.state === 'SUCCEEDED')).toBe(true);
    expect(snap.fees).toHaveLength(1);
    expect(ids).toContain(snap.fees[0].delivery_id);
    const repeated = await Promise.all(ids.map(id => complete(order, id)));
    expect(repeated.every(r => r.replay)).toBe(true);
    expect(repeated.filter(r => r.feeCandidate)).toHaveLength(1);
    expect((await snapshot(order)).fees).toEqual(snap.fees);
  });
  it('does not select a fee candidate while a failed final delivery awaits retry', async () => {
    const { order, ids } = await setupOrder(2); const first = ids[0]!, last = ids[1]!;
    expect((await complete(order, first)).feeCandidate).toBe(false);
    await changeAttempt(order, last, 'PENDING', 'FAILED');
    expect((await snapshot(order)).fees).toEqual([]);
    await expect(complete(order, last)).rejects.toThrow('ATTEMPT_STATE_INVALID');
    await changeAttempt(order, last, 'FAILED', 'PENDING');
    expect(await complete(order, last)).toEqual({ replay: false, feeCandidate: true });
    expect((await snapshot(order)).fees).toEqual([{ delivery_id: last }]);
  });
  it('handles duplicate completion requests without a second claim', async () => {
    const { order, ids } = await setupOrder(1); const id = ids[0]!;
    const results = await Promise.all(Array.from({ length: 8 }, () => complete(order, id)));
    expect(results.filter(r => !r.replay)).toHaveLength(1);
    expect(results.every(r => r.feeCandidate)).toBe(true);
    expect((await snapshot(order)).fees).toEqual([{ delivery_id: id }]);
  });
  it('keeps the fee unassigned if another delivery has already failed', async () => {
    const { order, ids } = await setupOrder(2);
    await changeAttempt(order, ids[1]!, 'PENDING', 'FAILED');
    expect((await complete(order, ids[0]!)).feeCandidate).toBe(false);
    expect((await snapshot(order)).fees).toEqual([]);
  });
  it('rolls back both state and candidate on a simulated pre-commit failure and permits retry', async () => {
    const { order, ids } = await setupOrder(1); const id = ids[0]!;
    await expect(complete(order, id, true)).rejects.toThrow('SYNTHETIC_ABORT');
    expect(await snapshot(order)).toEqual({ states: [{ id, state: 'PENDING' }], fees: [] });
    expect(await complete(order, id)).toEqual({ replay: false, feeCandidate: true });
    expect(await complete(order, id)).toEqual({ replay: true, feeCandidate: true });
    expect((await snapshot(order)).fees).toHaveLength(1);
  });
  it('rejects wrong-order deliveries and uses a database uniqueness backstop', async () => {
    const a = await setupOrder(1); const b = await setupOrder(1);
    await expect(complete(a.order, b.ids[0]!)).rejects.toThrow('DELIVERY_NOT_FOUND');
    await complete(a.order, a.ids[0]!);
    await expect(transaction(c => c.query(`INSERT INTO ${claims}(order_id,delivery_id) VALUES ($1,$2)`, [a.order, a.ids[0]]))).rejects.toThrow();
    expect((await snapshot(a.order)).fees).toHaveLength(1);
    expect((await snapshot(b.order)).fees).toHaveLength(0);
  });
});
